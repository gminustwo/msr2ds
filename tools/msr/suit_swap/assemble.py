"""Assembles src/msr/suit_swap_stub.s into src/msr/suit_swap_stub.h, linked at the address
msr/suit_swap.h places it (needs clang and lld with the ARM target, as in MSYS2 UCRT64)."""

import pathlib
import shutil
import struct
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'src' / 'msr' / 'suit_swap_stub.s'
HEADER = ROOT / 'src' / 'msr' / 'suit_swap_stub.h'
ADDRESS = 0x6C4880  # msr/suit_swap.h StubAddress


def tool(name):
    """The program's path, found with or without .exe."""
    return shutil.which(name) or shutil.which(name + '.exe') or name


def text_section(elf):
    """The .text bytes of a linked 32-bit little-endian ELF."""
    shoff = struct.unpack_from('<I', elf, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', elf, 0x2E)
    sections = [struct.unpack_from('<IIIIIIIIII', elf, shoff + i * shentsize) for i in range(shnum)]
    names = sections[shstrndx][4]

    def name(offset):
        return elf[names + offset:elf.index(b'\0', names + offset)].decode()

    text = None
    for section in sections:
        if name(section[0]) == '.text':
            text = elf[section[4]:section[4] + section[5]]
    return text


def main():
    with tempfile.TemporaryDirectory() as tmp:
        obj = pathlib.Path(tmp) / 'stub.o'
        linked = pathlib.Path(tmp) / 'stub.elf'
        subprocess.run([tool('clang'), '--target=armv6k-none-eabi', '-c', str(SOURCE), '-o', str(obj)],
                       check=True)
        # Through the clang driver, which runs ld.lld as an ELF linker for this target.
        subprocess.run([tool('clang'), '--target=armv6k-none-eabi', '-nostdlib', '-fuse-ld=lld',
                        '-Wl,-Ttext=0x%X' % ADDRESS, '-Wl,-e,entry', str(obj), '-o', str(linked)],
                       check=True)
        text = text_section(linked.read_bytes())
    words = struct.unpack('<%dI' % (len(text) // 4), text)
    lines = ['// Generated by tools/msr/suit_swap/assemble.py from suit_swap_stub.s. Do not edit.',
             '',
             '#pragma once',
             '',
             '#include <array>',
             '#include "common/common_types.h"',
             '',
             'namespace MSR::SuitSwap {',
             '',
             'inline constexpr std::array<u32, %d> Stub = {' % len(words)]
    for i in range(0, len(words), 6):
        lines.append('    ' + ' '.join('0x%08X,' % w for w in words[i:i + 6]))
    lines += ['};', '', '} // namespace MSR::SuitSwap', '']
    HEADER.write_text('\n'.join(lines), newline='\n')
    print('%s: %d words' % (HEADER.relative_to(ROOT), len(words)))


if __name__ == '__main__':
    main()
